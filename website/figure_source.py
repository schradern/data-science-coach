"""Map every committed image to the exact code that produced it.

The lessons used to link each figure to the *whole* generating file. For
`data/figures.py` that is 1000 lines covering sixteen modules, so "Code ansehen"
answered a question nobody asked: it showed the reader everything except the
twenty lines they wanted. Worse, every `.svg` linked to `lib/diagrams.py` —
including the five diagrams that were drawn by hand and appear nowhere in it.

This module finds, for each image, the smallest piece of code that produces it:

  * `lib/diagrams.py`        one function per SVG, named in its TARGETS table.
  * `module/*/code/*.py`     one `def fig_*()` per PNG -> the function.
  * `data/figures.py`        a flat script -> the block between one `save(...)`
                             and the previous one, starting at its section banner.

Images with no generator get no code link at all. They are listed in HANDMADE,
and `tools/check_repo.py` fails if that list ever disagrees with reality.
"""
from __future__ import annotations

import ast
import re
import textwrap
from dataclasses import dataclass
from pathlib import Path

# Images that are not generated by any script. Vector drawings, authored by hand
# in the editor. Keep this list exact: check_repo.py cross-checks it, so an image
# that gains a generator must be removed from it, and a new hand-drawn diagram
# must be added.
HANDMADE: frozenset[str] = frozenset({
    "module/01-einfuehrung/assets/analyse_zyklus.svg",
    "module/01-einfuehrung/assets/drei_disziplinen.svg",
    "module/15-kausale-inferenz/assets/dag_beispiel.svg",
    "module/23-machine-learning/assets/train_test_split.svg",
    "module/33-rag-llm-pipelines/assets/rag_suche_flow.svg",
})

_IMAGE_SUFFIX = (".png", ".svg")
_SLUG = re.compile(r"^\d\d-[a-z0-9-]+$")
# `# ====...` / `# MODULE 01 · Cohort overview` / `# ====...`
_BANNER_RULE = re.compile(r"^#\s*=+\s*$")


@dataclass(frozen=True)
class Snippet:
    """The code that draws one figure."""
    source: str          # repo-relative path of the generating file
    start: int           # 1-based, inclusive
    end: int             # 1-based, inclusive
    code: str
    symbol: str          # function name, or the section banner's title
    # "function" whole function · "part" only the drawing inside a larger one
    # · "section" a block of a top-to-bottom script
    kind: str = "function"
    lang: str = "python"

    @property
    def zeilen(self) -> str:
        return f"{self.start}–{self.end}" if self.end > self.start else str(self.start)


# --------------------------------------------------------------------------
# Resolving `save(fig, ASSETS / "07-eda" / "assets" / "x.png")` to a path
# --------------------------------------------------------------------------
def _string_parts(node: ast.AST, env: dict[str, list[str]]) -> list[str]:
    """The string components of a path expression, in order.

    Unresolvable pieces (`Path(__file__).parents[1]`) contribute nothing, which
    is exactly right: the slug is then taken from the file's own location.
    """
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return [node.value]
    if isinstance(node, ast.Name):
        return list(env.get(node.id, []))
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Div):
        return _string_parts(node.left, env) + _string_parts(node.right, env)
    return []


def _module_env(tree: ast.Module) -> dict[str, list[str]]:
    """Top-level `NAME = <path expression>` bindings, e.g. M21_DIR."""
    env: dict[str, list[str]] = {}
    for stmt in tree.body:
        if isinstance(stmt, ast.Assign) and len(stmt.targets) == 1 \
                and isinstance(stmt.targets[0], ast.Name):
            parts = _string_parts(stmt.value, env)
            if parts:
                env[stmt.targets[0].id] = parts
    return env


def _save_target(call: ast.Call) -> ast.AST | None:
    """The path argument of a figure-writing call, or None."""
    name = getattr(call.func, "id", None) or getattr(call.func, "attr", None)
    if name == "save" and len(call.args) >= 2:
        return call.args[1]          # lib.plotstyle.save(fig, path)
    if name == "savefig" and call.args:
        return call.args[0]          # fig.savefig(path)
    return None


def _asset_key(parts: list[str], quelle: Path, root: Path) -> str | None:
    """`module/<slug>/assets/<name>` for the image this call writes."""
    dateien = [p for p in parts if p.endswith(_IMAGE_SUFFIX)]
    if not dateien:
        return None
    name = dateien[-1]
    slugs = [p for p in parts if _SLUG.match(p)]
    if slugs:
        return f"module/{slugs[-1]}/assets/{name}"
    # No slug in the expression (`ASSETS / "x.png"`, ASSETS being module-local):
    # the generator lives inside the module it draws for.
    rel = quelle.relative_to(root).parts
    if len(rel) >= 2 and rel[0] == "module":
        return f"module/{rel[1]}/assets/{name}"
    return None


# --------------------------------------------------------------------------
# Slicing the code out of the file
# --------------------------------------------------------------------------
def _enclosing_function(call: ast.AST, tree: ast.Module) -> ast.FunctionDef | None:
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef):
            for child in ast.walk(node):
                if child is call:
                    return node
    return None


def _is_figure_function(name: str) -> bool:
    """A function that exists solely to draw one figure: show all of it."""
    return name.startswith(("fig_", "_fig")) or "figure" in name


def _creates_figure(stmt: ast.stmt) -> bool:
    """`fig, ax = plt.subplots(...)`, `fig = plt.figure()`, or `apply_style()`."""
    if isinstance(stmt, ast.Expr) and isinstance(stmt.value, ast.Call) \
            and getattr(stmt.value.func, "id", None) == "apply_style":
        return True
    if not isinstance(stmt, ast.Assign):
        return False
    namen: list[str] = []
    for ziel in stmt.targets:
        if isinstance(ziel, ast.Name):
            namen.append(ziel.id)
        elif isinstance(ziel, (ast.Tuple, ast.List)):
            namen += [e.id for e in ziel.elts if isinstance(e, ast.Name)]
    return "fig" in namen


def _narrow_in_function(fn: ast.FunctionDef, call: ast.Call) -> tuple[int, int] | None:
    """Inside a general function (`main()`), keep only the drawing.

    A lesson script computes, prints, then plots. Showing the reader all sixty
    lines of `main()` to explain a ten-line figure is the very clutter this
    module exists to remove.
    """
    ziel = next((i for i, s in enumerate(fn.body)
                 if s.lineno <= call.lineno <= (s.end_lineno or s.lineno)), None)
    if ziel is None:
        return None
    start = next((i for i in range(ziel, -1, -1) if _creates_figure(fn.body[i])), None)
    if start is None:
        return None
    # `apply_style()` immediately above the figure belongs to it.
    if start > 0 and _creates_figure(fn.body[start - 1]):
        start -= 1
    return fn.body[start].lineno, fn.body[ziel].end_lineno


def _banner_start(lines: list[str], save_line: int, floor: int) -> tuple[int, str] | None:
    """The `# ==== / # MODULE 06 · … / # ====` banner that opens this block.

    Searched backwards from the save, never past `floor` (the previous figure).
    Returns the banner's first line and its title.
    """
    for i in range(save_line - 1, floor - 1, -1):
        if i + 2 < len(lines) and _BANNER_RULE.match(lines[i]) \
                and _BANNER_RULE.match(lines[i + 2]) and lines[i + 1].startswith("#"):
            return i + 1, lines[i + 1].lstrip("# ").strip()
    return None


def _trim(lines: list[str], start: int, end: int) -> int:
    """Drop blank lines at the top of a block."""
    while start < end and not lines[start - 1].strip():
        start += 1
    return start


def _scan_python(quelle: Path, root: Path) -> dict[str, Snippet]:
    text = quelle.read_text(encoding="utf-8")
    lines = text.split("\n")
    tree = ast.parse(text)
    env = _module_env(tree)
    rel = str(quelle.relative_to(root))

    # Every figure-writing call, in file order.
    treffer: list[tuple[ast.Call, ast.AST, str]] = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        ziel = _save_target(node)
        if ziel is None:
            continue
        key = _asset_key(_string_parts(ziel, env), quelle, root)
        if key:
            treffer.append((node, ziel, key))
    treffer.sort(key=lambda t: t[0].lineno)

    index: dict[str, Snippet] = {}
    vorheriges_ende = 0
    for call, _ziel, key in treffer:
        fn = _enclosing_function(call, tree)
        kind = "function"
        if fn is not None and not _is_figure_function(fn.name):
            eng = _narrow_in_function(fn, call)
            if eng:
                start, end = eng
                symbol, kind = f"{fn.name}()", "part"
            else:
                start = min([d.lineno for d in fn.decorator_list] or [fn.lineno])
                end, symbol = fn.end_lineno, f"{fn.name}()"
        elif fn is not None:
            start = min([d.lineno for d in fn.decorator_list] or [fn.lineno])
            end, symbol = fn.end_lineno, f"{fn.name}()"
        else:
            kind = "section"
            # Module-level script: the block reaches back to the previous figure,
            # or to this section's banner comment, whichever is nearer.
            stmt = next(s for s in tree.body
                        if s.lineno <= call.lineno <= (s.end_lineno or s.lineno))
            end = stmt.end_lineno
            banner = _banner_start(lines, call.lineno, vorheriges_ende)
            if banner:
                start, symbol = banner
            else:
                start = _trim(lines, vorheriges_ende + 1, end)
                symbol = Path(key).stem
            vorheriges_ende = end

        # A block lifted out of a function body carries its indentation with it.
        code = textwrap.dedent("\n".join(lines[start - 1:end])).rstrip()
        index[key] = Snippet(rel, start, end, code, symbol, kind)
    return index


# --------------------------------------------------------------------------
# lib/diagrams.py: one function per SVG, wired up in its TARGETS table
# --------------------------------------------------------------------------
def _scan_diagrams(quelle: Path, root: Path) -> dict[str, Snippet]:
    text = quelle.read_text(encoding="utf-8")
    lines = text.split("\n")
    tree = ast.parse(text)
    funktionen = {n.name: n for n in tree.body if isinstance(n, ast.FunctionDef)}

    ziele: dict[str, str] = {}
    for stmt in tree.body:
        if isinstance(stmt, ast.Assign) and getattr(stmt.targets[0], "id", "") == "TARGETS":
            for slug_node, paare in zip(stmt.value.keys, stmt.value.values):
                for paar in paare.elts:
                    name, fn = paar.elts[0].value, paar.elts[1].id
                    ziele[f"module/{slug_node.value}/assets/{name}.svg"] = fn

    rel = str(quelle.relative_to(root))
    index: dict[str, Snippet] = {}
    for key, fn_name in ziele.items():
        fn = funktionen.get(fn_name)
        if fn is None:
            continue
        code = "\n".join(lines[fn.lineno - 1:fn.end_lineno]).rstrip()
        index[key] = Snippet(rel, fn.lineno, fn.end_lineno, code, f"{fn.name}()")
    return index


# --------------------------------------------------------------------------
def build_index(root: Path) -> dict[str, Snippet]:
    """image path (repo-relative) -> the code that draws it."""
    index: dict[str, Snippet] = {}

    quellen = [root / "data" / "figures.py"]
    quellen += sorted(root.glob("module/*/code/*.py"))
    for quelle in quellen:
        if quelle.exists():
            index.update(_scan_python(quelle, root))

    diagrams = root / "lib" / "diagrams.py"
    if diagrams.exists():
        index.update(_scan_diagrams(diagrams, root))
    return index


def displayed_images(root: Path) -> set[str]:
    """Every image a lesson actually shows, as a repo-relative path.

    The alt texts are long and describe results, so they contain brackets:
    `![… (Weiblich 0,88 [0,79–0,95]) …](assets/subgruppen_auc.png)`. A `[^\\]]*`
    pattern stops at the first `]` and misses the image entirely — which is how
    Modul 32 quietly lost its code link. Match up to the first `](` instead.
    """
    muster = re.compile(r"!\[.*?\]\(([^)\s]+)")
    gefunden: set[str] = set()
    for md in sorted(root.glob("module/*/*.md")):
        slug = md.relative_to(root).parts[1]
        for m in muster.finditer(md.read_text(encoding="utf-8")):
            src = m.group(1)
            if src.endswith(_IMAGE_SUFFIX) and not src.startswith(("http", "/")):
                gefunden.add(f"module/{slug}/{src}")
    return gefunden


if __name__ == "__main__":
    wurzel = Path(__file__).resolve().parent.parent
    index = build_index(wurzel)
    gezeigt = displayed_images(wurzel)
    ohne = sorted(gezeigt - set(index) - HANDMADE)

    print(f"{len(gezeigt)} Abbildungen in Lektionen, {len(index)} davon aus Code erzeugt.")
    for key in sorted(gezeigt & set(index)):
        s = index[key]
        print(f"  {key:62s} {s.source}:{s.zeilen}  ({s.symbol})")
    print(f"\n{len(HANDMADE)} von Hand gezeichnet (kein Code-Link):")
    for key in sorted(HANDMADE):
        print(f"  {key}")
    if ohne:
        print(f"\n{len(ohne)} OHNE Zuordnung — weder Code noch HANDMADE:")
        for key in ohne:
            print(f"  {key}")
